CREATE TABLE "platform_telegram_integrations" (
  "id" integer PRIMARY KEY DEFAULT 1 NOT NULL,
  "bot_token_ciphertext" text NOT NULL,
  "bot_token_iv" varchar(32) NOT NULL,
  "bot_token_auth_tag" varchar(32) NOT NULL,
  "bot_id" varchar(32),
  "bot_username" varchar(64),
  "chat_id" varchar(32),
  "chat_name" varchar(255),
  "pairing_code_hash" varchar(64),
  "pairing_expires_at" timestamp with time zone,
  "authorized_admin_id" uuid,
  "enabled" boolean DEFAULT false NOT NULL,
  "status" varchar(24) DEFAULT 'saved' NOT NULL,
  "last_checked_at" timestamp with time zone,
  "last_verified_at" timestamp with time zone,
  "last_error_code" varchar(64),
  "last_delivery_at" timestamp with time zone,
  "last_delivery_status" varchar(16),
  "last_delivery_error_code" varchar(64),
  "last_inbound_at" timestamp with time zone,
  "last_update_id" bigint DEFAULT 0 NOT NULL,
  "poll_lease_owner" varchar(128),
  "poll_lease_until" timestamp with time zone,
  "updated_by" uuid NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "platform_telegram_singleton_check" CHECK ("id" = 1),
  CONSTRAINT "platform_telegram_status_check" CHECK ("status" in ('saved', 'verified', 'failed')),
  CONSTRAINT "platform_telegram_delivery_status_check" CHECK ("last_delivery_status" is null or "last_delivery_status" in ('sent', 'failed')),
  CONSTRAINT "platform_telegram_updated_by_fk" FOREIGN KEY ("updated_by") REFERENCES "public"."users"("id") ON DELETE restrict,
  CONSTRAINT "platform_telegram_authorized_admin_fk" FOREIGN KEY ("authorized_admin_id") REFERENCES "public"."users"("id") ON DELETE restrict
);
